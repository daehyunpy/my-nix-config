"""Manual saved-plan safeguards for this Tailscale root; not an authorization boundary."""

import argparse
from contextlib import contextmanager
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


def tofu(root, *arguments, capture=False, check=True):
    return subprocess.run(
        ["tofu", f"-chdir={root}", *arguments],
        check=check,
        text=True,
        stdout=subprocess.PIPE if capture else None,
    )


def source_fingerprint(root):
    return {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(root.iterdir())
        if path.is_file()
        and (
            path.name in (".terraform.lock.hcl", ".opentofu-version")
            or path.name.endswith(
                (
                    ".tf",
                    ".tf.json",
                    ".tofu",
                    ".tofu.json",
                    ".tfvars",
                    ".tfvars.json",
                    ".hujson",
                )
            )
        )
    }


def plan_tailnet(document):
    provider = (
        document.get("configuration", {})
        .get("provider_config", {})
        .get("tailscale", {})
    )
    tailnet = provider.get("expressions", {}).get("tailnet", {}).get("constant_value")
    if not isinstance(tailnet, str) or not tailnet:
        raise ValueError("The saved plan must pin a single Tailscale tailnet.")
    if any(
        "delete" in resource["change"]["actions"]
        for resource in document.get("resource_changes", [])
    ):
        raise ValueError("Deletion/replacement is not allowed by this manual workflow.")
    return tailnet


def require_local_state(root):
    if not (root / "terraform.tfstate").is_file():
        raise ValueError(
            "Authoritative local state is missing; restore/adopt it separately first."
        )
    if tofu(root, "workspace", "show", capture=True).stdout.strip() != "default":
        raise ValueError("This workflow requires the default local workspace.")


def verify_review(root, plan, review):
    if source_fingerprint(root) != review["source"]:
        raise ValueError(
            "Configuration or dependency inputs changed; generate a new plan."
        )
    if hashlib.sha256(plan.read_bytes()).hexdigest() != review["plan_sha256"]:
        raise ValueError("Saved plan bytes changed; generate a new plan.")


def load_review(root, plan):
    plan = plan.resolve()
    expected = (root / ".terraform" / "reviewed-plans").resolve()
    if plan.name != "plan.tfplan" or plan.parent.parent != expected:
        raise ValueError("Use a plan generated by this workflow in this checkout.")
    review = json.loads((plan.parent / "review.json").read_text())
    if review["root"] != str(root.resolve()):
        raise ValueError(
            "This plan was generated in another checkout; generate a new plan."
        )
    verify_review(root, plan, review)
    return review


@contextmanager
def review_snapshot(root, plan):
    review = load_review(root, plan)
    with tempfile.TemporaryDirectory(
        prefix="apply-", dir=plan.parent.parent
    ) as directory:
        snapshot = Path(directory) / "plan.tfplan"
        shutil.copyfile(plan, snapshot)
        snapshot.chmod(0o400)
        verify_review(root, snapshot, review)
        yield snapshot, review


def create_plan(root):
    require_local_state(root)
    source = source_fingerprint(root)
    directory = root / ".terraform" / "reviewed-plans"
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    bundle = Path(tempfile.mkdtemp(prefix="plan-", dir=directory))
    complete = False
    try:
        plan = bundle / "plan.tfplan"
        result = tofu(
            root,
            "plan",
            "-input=false",
            "-lock=true",
            "-detailed-exitcode",
            f"-out={plan}",
            check=False,
        )
        if result.returncode not in (0, 2):
            raise subprocess.CalledProcessError(result.returncode, result.args)
        document = json.loads(
            tofu(root, "show", "-json", str(plan), capture=True).stdout
        )
        review = {
            "root": str(root.resolve()),
            "tailnet": plan_tailnet(document),
            "plan_sha256": hashlib.sha256(plan.read_bytes()).hexdigest(),
            "source": source,
        }
        verify_review(root, plan, review)
        (bundle / "review.json").write_text(json.dumps(review, indent=2) + "\n")
        complete = True
        print(f"Private saved plan: {plan}")
        print(f"Tailnet: {review['tailnet']}; SHA-256: {review['plan_sha256']}")
        print(
            "Nothing applied. Back up state and obtain separate authorization before apply."
        )
    finally:
        if not complete:
            shutil.rmtree(bundle)


def apply_plan(root, plan):
    if not (sys.stdin.isatty() and sys.stdout.isatty()):
        raise ValueError(
            "Apply requires interactive input and output; no unattended approval."
        )
    require_local_state(root)
    with review_snapshot(root, plan) as (snapshot, review):
        document = json.loads(
            tofu(root, "show", "-json", str(snapshot), capture=True).stdout
        )
        if plan_tailnet(document) != review["tailnet"]:
            raise ValueError("Review metadata does not match the saved plan's tailnet.")
        tofu(root, "show", "-no-color", str(snapshot))
        token = f"apply {review['tailnet']} {review['plan_sha256'][:12]}"
        print(
            "Confirm only after authorization and a private off-checkout state backup."
        )
        try:
            response = input(f"Type '{token}' to apply exactly this plan: ")
        except EOFError as error:
            raise ValueError("Confirmation ended; apply not started.") from error
        if response != token:
            raise ValueError("Confirmation did not match; apply not started.")
        verify_review(root, snapshot, review)
        try:
            tofu(root, "apply", "-input=false", "-lock=true", str(snapshot))
        finally:
            print(
                "Back up state after the attempt and inspect a fresh plan; failed applies may be partial."
            )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("plan", help="Save a private plan without applying it")
    apply = commands.add_parser(
        "apply", help="Review and explicitly confirm a saved plan"
    )
    apply.add_argument("plan", type=Path)
    arguments = parser.parse_args()
    os.umask(0o077)
    root = Path(__file__).resolve().parent
    try:
        if arguments.command == "plan":
            create_plan(root)
        else:
            apply_plan(root, arguments.plan.resolve())
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print(
            "Interrupted; if apply started, inspect state before retrying.",
            file=sys.stderr,
        )
        return 130
    return 0


if __name__ == "__main__":
    sys.exit(main())
